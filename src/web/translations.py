    text = TRANSLATIONS.get(locale, {}).get(key)
    if text is None:
        # Fallback to English if key missing in pt-BR
        text = TRANSLATIONS.get("en", {}).get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
